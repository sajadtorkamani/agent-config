#!/usr/bin/env bash
# Symlinks each skill in this repo (and in ../agent-config-private, if cloned) into ~/.claude/skills,
# CLAUDE.md into ~/.claude, and AGENTS.md into ~/.codex.
set -euo pipefail

repo_dir="$(cd "$(dirname "$0")" && pwd)"
private_repo_dir="$(dirname "$repo_dir")/agent-config-private"
skills_dir="$HOME/.claude/skills"
mkdir -p "$skills_dir"

link() {
  local src="$1"
  local dest="$2"
  local name="$(basename "$src")"

  if [ -L "$dest" ]; then
    ln -sfn "$src" "$dest"
    echo "Updated link: $name"
  elif [ -e "$dest" ]; then
    echo "Skipped $name: $dest already exists and is not a symlink"
  else
    ln -s "$src" "$dest"
    echo "Linked: $name"
  fi
}

for skill in "$repo_dir"/skills/*/ "$private_repo_dir"/skills/*/; do
  [ -d "$skill" ] || continue
  link "${skill%/}" "$skills_dir/$(basename "$skill")"
done

if [ -f "$repo_dir/CLAUDE.md" ]; then
  link "$repo_dir/CLAUDE.md" "$HOME/.claude/CLAUDE.md"
fi

# Codex reads ~/.codex/AGENTS.md directly and doesn't support imports, so when the private repo
# is cloned, write a merged copy instead of a symlink. Re-run this script after editing either file.
codex_agents="$HOME/.codex/AGENTS.md"
generated_marker="<!-- Generated by agent-config/install.sh. Edit the source AGENTS.md files instead. -->"
if [ -f "$repo_dir/AGENTS.md" ]; then
  mkdir -p "$HOME/.codex"
  if [ -f "$private_repo_dir/AGENTS.md" ]; then
    if [ -e "$codex_agents" ] && [ ! -L "$codex_agents" ] && [ "$(head -n 1 "$codex_agents")" != "$generated_marker" ]; then
      echo "Skipped AGENTS.md: $codex_agents already exists and wasn't generated by this script"
    else
      rm -f "$codex_agents"
      {
        echo "$generated_marker"
        echo
        cat "$repo_dir/AGENTS.md"
        echo
        cat "$private_repo_dir/AGENTS.md"
      } > "$codex_agents"
      echo "Generated: AGENTS.md (public + private)"
    fi
  elif [ -L "$codex_agents" ] || [ "$(head -n 1 "$codex_agents" 2>/dev/null)" = "$generated_marker" ]; then
    ln -sfn "$repo_dir/AGENTS.md" "$codex_agents"
    echo "Updated link: AGENTS.md"
  else
    link "$repo_dir/AGENTS.md" "$codex_agents"
  fi
fi
